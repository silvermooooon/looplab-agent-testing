export function exportScript(
  nodes: any[],
  files: Array<{
    id: string;
    name: string;
    mime_type: string;
    sha256: string;
  }> = [],
) {
  const specs = nodes.map((n) => ({
    key: n.key,
    version: n.version,
    spec: n.spec,
    params: n.params,
  }));
  const metadata = Object.fromEntries(
    files.map(({ id, ...file }) => [id, file]),
  );
  return `// Generated by Agent Test Platform. Versions are pinned.
// npm install playwright && npx playwright install chromium
// TEST_BASE_URL=https://target TEST_SECRET_username=... npx tsx flow.ts
// For library files, set TEST_FILE_PATHS to JSON mapping each file ID to its local path.
import { chromium } from 'playwright';
import { expect } from 'playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const nodes = ${JSON.stringify(specs, null, 2)};
const fileMetadata:Record<string,{name:string,mime_type:string,sha256:string}> = ${JSON.stringify(metadata, null, 2)};
const filePaths:Record<string,string> = JSON.parse(process.env.TEST_FILE_PATHS || '{}');
const unsupported=nodes.flatMap(node=>node.spec.steps).find((step:any)=>['pauseForHuman','watchElement','watchDialog','watchResponse','clearWatchers'].includes(step.action));
if(unsupported) throw new Error('This flow requires LoopLab human intervention and cannot be run as an exported script: '+unsupported.action);
const baseUrl=process.env.TEST_BASE_URL;
if(!baseUrl) throw new Error('TEST_BASE_URL is required');
const origin=new URL(baseUrl).origin;
const outputs:Record<string,string>={};
const browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL||undefined});
const context=await browser.newContext();
await context.route('**/*',route=>route.request().isNavigationRequest() && new URL(route.request().url()).origin!==origin ? route.abort() : route.continue());
const page=await context.newPage();
page.setDefaultTimeout(12000);
await mkdir('artifacts',{recursive:true});
async function loadTestFile(id:string) {
  const metadata=fileMetadata[id];
  if(!metadata) throw new Error('No exported metadata for test file '+id);
  const path=filePaths[id];
  if(!path) throw new Error('Set TEST_FILE_PATHS with a local path for test file '+id);
  const data=await readFile(path);
  if(createHash('sha256').update(data).digest('hex')!==metadata.sha256) throw new Error('SHA-256 mismatch for test file '+id);
  return { ...metadata, data };
}
try {
  await page.goto(baseUrl,{waitUntil:'domcontentloaded'});
  for(const node of nodes) {
    const resolve=(value:string)=>value.replace(/\\{\\{\\s*([a-zA-Z][\\w.]*)\\s*\\}\\}/g,(_,path:string)=>{
      if(path==='baseUrl') return baseUrl;
      const [scope,key]=path.split('.');
      const value=scope==='param'?(node.params as Record<string,string>)[key!]:scope==='output'?outputs[key!]:scope==='secret'?process.env['TEST_SECRET_'+key]:scope==='var'?process.env['TEST_VAR_'+key]:undefined;
      if(value===undefined) throw new Error('Missing variable '+path);
      if(scope==='param') return value.replace(/\\{\\{\\s*output\\.([a-zA-Z][\\w]*)\\s*\\}\\}/g,(_,outputKey:string)=>{
        if(!Object.hasOwn(outputs,outputKey)) throw new Error('Missing variable: output.'+outputKey);
        return outputs[outputKey]!;
      });
      return value;
    });
    for(const step of node.spec.steps as any[]) {
      if(step.action==='navigate') {const url=new URL(resolve(step.url),baseUrl);if(url.origin!==origin)throw new Error('Invalid navigation origin');await page.goto(url.href,{waitUntil:'domcontentloaded'});continue;}
      if(step.action==='reload') {await page.reload({waitUntil:'domcontentloaded'});continue;}
      if(step.action==='screenshot') {await page.screenshot({path:'artifacts/'+resolve(step.name).replace(/[^a-zA-Z0-9_.-]/g,'_')+'.png',fullPage:true,mask:[page.locator('input[type=password]')]});continue;}
      if(step.action==='waitForResponse') {const url=resolve(step.url);await page.waitForResponse(response=>response.url().includes(url),{timeout:step.timeoutMs});continue;}
      if(step.action==='uploadFile' || step.action==='readFile') {
        const file=await loadTestFile(resolve(step.fileId));
        if(step.action==='uploadFile') await page.locator(resolve(step.selector)).setInputFiles({name:file.name,mimeType:file.mime_type,buffer:file.data});
        else {
          let text:string;
          try {text=new TextDecoder('utf-8',{fatal:true}).decode(file.data);if(text.includes('\\0'))throw new Error();}
          catch {throw new Error('Test file is not valid UTF-8 text');}
          outputs[step.output]=text;
        }
        continue;
      }
      const locator=page.locator(resolve(step.selector));
      switch(step.action) {
        case 'fill': await locator.fill(resolve(step.value));break;
        case 'click': await locator.click();break;
        case 'press': await locator.press(resolve(step.key));break;
        case 'assertText': await expect(locator).toContainText(resolve(step.text),{timeout:step.timeoutMs??20000});break;
        case 'assertVisible': await expect(locator).toBeVisible(step.timeoutMs?{timeout:step.timeoutMs}:undefined);break;
        case 'waitFor': await locator.waitFor({state:'visible',timeout:step.timeoutMs});break;
        case 'waitForHidden': await locator.waitFor({state:'hidden',timeout:step.timeoutMs});break;
        case 'extractText': outputs[step.output]=await locator.innerText();break;
        default: throw new Error('Unsupported action: '+step.action);
      }
    }
    console.log('PASS',node.key,'v'+node.version);
  }
} finally { await browser.close(); }
`;
}
